@php
/**
 * Pure SVG card — no HTML wrapper.
 * Variables: $stats, $theme, $hide, $avatar, $owner, $repo, $username
 */

$themes = [
    'light'   => ['bg' => '#ffffff', 'bg2' => '#f6f8fa', 'border' => '#d0d7de', 'text' => '#1f2328',  'sub' => '#656d76',  'accent' => '#7c3aed', 'accent2' => '#06b6d4', 'spark' => '#7c3aed'],
    'dark'    => ['bg' => '#0d1117', 'bg2' => '#161b22', 'border' => '#30363d', 'text' => '#e6edf3',  'sub' => '#7d8590',  'accent' => '#9d5cf5', 'accent2' => '#22d3ee', 'spark' => '#9d5cf5'],
    'radical' => ['bg' => '#141321', 'bg2' => '#1e1a36', 'border' => '#fe428e', 'text' => '#a9fef7',  'sub' => '#fe428e',  'accent' => '#fe428e', 'accent2' => '#f8d847', 'spark' => '#fe428e'],
    'merko'   => ['bg' => '#0a0f0a', 'bg2' => '#0f1a0f', 'border' => '#2dba4e', 'text' => '#b7c8b9',  'sub' => '#68b587',  'accent' => '#2dba4e', 'accent2' => '#45d371', 'spark' => '#2dba4e'],
];

$t = $themes[$theme] ?? $themes['light'];

$showLines      = !in_array('lines',       $hide);
$showSparkline  = !in_array('sparkline',   $hide);
$showFirstCommit = !in_array('firstcommit', $hide);

$totalCommits = $stats['total_commits'] ?? 0;
$linesNet     = $stats['lines_net']     ?? null;
$linesAdded   = $stats['lines_added']   ?? null;
$linesDeleted = $stats['lines_deleted'] ?? null;
$firstCommit  = $stats['first_commit']  ?? null;
$stars        = $stats['stars']         ?? 0;
$forks        = $stats['forks']         ?? 0;
$weeklyCommits = $stats['weekly_commits'] ?? [];

// Sparkline points (200×30 viewBox within the card)
$sparkPoints = '';
$sparkW = 200; $sparkH = 30;
$wc = count($weeklyCommits);
if ($wc > 1) {
    $maxC = max(array_filter($weeklyCommits) ?: [1]);
    foreach ($weeklyCommits as $i => $c) {
        $x = round($i / ($wc - 1) * $sparkW, 2);
        $y = round($sparkH - ($c / $maxC) * ($sparkH - 4), 2);
        $sparkPoints .= "{$x},{$y} ";
    }
}

// First commit formatted
$firstCommitFormatted = $firstCommit
    ? \Carbon\Carbon::parse($firstCommit)->format('M j, Y')
    : null;

// Languages — top 5
$topLangs = array_slice($stats['languages'] ?? [], 0, 5);
$langColors = ['#7c3aed','#06b6d4','#f43f5e','#10b981','#f59e0b'];

// Card height calculation
$baseH = 190;
if ($showLines && $linesNet !== null) $baseH += 30;
if ($showFirstCommit && $firstCommitFormatted) $baseH += 24;
if (!empty($topLangs)) $baseH += 40;
if ($showSparkline && $sparkPoints) $baseH += 50;
$cardH = $baseH;
echo '<?xml version="1.0" encoding="UTF-8"?>';
@endphp
<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink"
     width="400" height="{{ $cardH }}" viewBox="0 0 400 {{ $cardH }}"
     role="img" aria-label="{{ $username }}'s contribution stats on {{ $owner }}/{{ $repo }}">

    <title>{{ $username }}'s stats on {{ $owner }}/{{ $repo }}</title>
    <desc>Total commits: {{ number_format($totalCommits) }}. Generated by RepoWrapped.</desc>

    <defs>
        <clipPath id="avatarClip">
            <circle cx="40" cy="40" r="24"/>
        </clipPath>
        <filter id="cardShadow" x="-5%" y="-5%" width="110%" height="110%">
            <feDropShadow dx="0" dy="2" stdDeviation="4" flood-color="{{ $t['accent'] }}" flood-opacity="0.15"/>
        </filter>
        <linearGradient id="accentGrad" x1="0" y1="0" x2="1" y2="0">
            <stop offset="0%" stop-color="{{ $t['accent'] }}"/>
            <stop offset="100%" stop-color="{{ $t['accent2'] }}"/>
        </linearGradient>
        <linearGradient id="sparkFill" x1="0" y1="0" x2="0" y2="1">
            <stop offset="0%" stop-color="{{ $t['spark'] }}" stop-opacity="0.4"/>
            <stop offset="100%" stop-color="{{ $t['spark'] }}" stop-opacity="0"/>
        </linearGradient>
    </defs>

    {{-- Card background --}}
    <rect width="400" height="{{ $cardH }}" rx="12" ry="12"
          fill="{{ $t['bg'] }}" stroke="{{ $t['border'] }}" stroke-width="1"
          filter="url(#cardShadow)"/>

    {{-- Accent bar at top --}}
    <rect x="0" y="0" width="400" height="3" rx="2" fill="url(#accentGrad)"/>

    {{-- Avatar --}}
    @if($avatar)
    <image x="16" y="16" width="48" height="48"
           clip-path="url(#avatarClip)"
           href="{{ $avatar }}"
           preserveAspectRatio="xMidYMid slice"/>
    <circle cx="40" cy="40" r="24" fill="none"
            stroke="{{ $t['accent'] }}" stroke-width="1.5" opacity="0.5"/>
    @else
    <circle cx="40" cy="40" r="24" fill="{{ $t['bg2'] }}" stroke="{{ $t['border'] }}" stroke-width="1.5"/>
    <text x="40" y="46" text-anchor="middle" font-size="20" fill="{{ $t['sub'] }}">👤</text>
    @endif

    {{-- Username + repo --}}
    <text x="74" y="33" font-family="'Segoe UI', system-ui, sans-serif"
          font-size="15" font-weight="700" fill="{{ $t['text'] }}">{{ $username }}</text>
    <text x="74" y="51" font-family="'Segoe UI', system-ui, sans-serif"
          font-size="11" fill="{{ $t['sub'] }}">{{ $owner }}/{{ $repo }}</text>

    {{-- Star + Fork --}}
    <text x="74" y="67" font-family="'Segoe UI', system-ui, sans-serif"
          font-size="10" fill="{{ $t['sub'] }}">
        ⭐ {{ number_format($stars) }}  🍴 {{ number_format($forks) }}
    </text>

    {{-- Divider --}}
    <line x1="16" y1="82" x2="384" y2="82" stroke="{{ $t['border'] }}" stroke-width="0.8"/>

    @php $yPos = 106; @endphp

    {{-- Total Commits --}}
    <text x="16" y="{{ $yPos }}" font-family="'Segoe UI', system-ui, sans-serif"
          font-size="10" fill="{{ $t['sub'] }}" text-transform="uppercase" letter-spacing="0.5">
        TOTAL COMMITS
    </text>
    <text x="384" y="{{ $yPos }}" font-family="'Segoe UI', system-ui, sans-serif"
          font-size="16" font-weight="700" fill="{{ $t['accent'] }}" text-anchor="end">
        {{ number_format($totalCommits) }}
    </text>

    @php $yPos += 28; @endphp

    {{-- Lines net --}}
    @if($showLines && $linesNet !== null)
    <text x="16" y="{{ $yPos }}" font-family="'Segoe UI', system-ui, sans-serif"
          font-size="10" fill="{{ $t['sub'] }}">LINES WRITTEN</text>
    <text x="384" y="{{ $yPos }}" font-family="'Segoe UI', system-ui, sans-serif"
          font-size="14" font-weight="600" fill="{{ $t['text'] }}" text-anchor="end">
        {{ number_format($linesNet) }}
    </text>
    @php $yPos += 28; @endphp
    @endif

    {{-- First commit --}}
    @if($showFirstCommit && $firstCommitFormatted)
    <text x="16" y="{{ $yPos }}" font-family="'Segoe UI', system-ui, sans-serif"
          font-size="10" fill="{{ $t['sub'] }}">FIRST COMMIT</text>
    <text x="384" y="{{ $yPos }}" font-family="'Segoe UI', system-ui, sans-serif"
          font-size="12" font-weight="500" fill="{{ $t['text'] }}" text-anchor="end">
        {{ $firstCommitFormatted }}
    </text>
    @php $yPos += 24; @endphp
    @endif

    {{-- Language bar --}}
    @if(!empty($topLangs))
    <line x1="16" y1="{{ $yPos }}" x2="384" y2="{{ $yPos }}"
          stroke="{{ $t['border'] }}" stroke-width="0.6"/>
    @php
        $yPos += 10; $barX = 16; $barW = 368;
        // Normalize top 5 to fill 100% of the visible bar
        $totalVisibleBytes = array_sum(array_column($topLangs, 'bytes'));
    @endphp
    <rect x="{{ $barX }}" y="{{ $yPos }}" width="{{ $barW }}" height="6"
          rx="3" fill="{{ $t['bg2'] }}"/>
    @foreach($topLangs as $i => $lang)
        @php
            $normalizedPercentage = ($lang['bytes'] / $totalVisibleBytes) * 100;
            $segW = round($normalizedPercentage / 100 * $barW, 2);
        @endphp
        <rect x="{{ $barX }}" y="{{ $yPos }}" width="{{ $segW }}" height="6"
              fill="{{ $langColors[$i % count($langColors)] }}"
              @if($i === 0) rx="3 0 0 3" @elseif($i === count($topLangs)-1) rx="0 3 3 0" @endif />

        @php
            $yOffset = 18;
        @endphp
        <text x="{{ $barX + $segW/2 }}" y="{{ $yPos + $yOffset }}"
              font-family="'Segoe UI', system-ui, sans-serif"
              font-size="8" fill="{{ $t['sub'] }}" text-anchor="middle">
            {{ $lang['name'] }}
        </text>
        @php $barX += $segW; @endphp
    @endforeach
    @php $yPos += 30; @endphp
    @endif

    {{-- Sparkline --}}
    @if($showSparkline && $sparkPoints)
    <line x1="16" y1="{{ $yPos }}" x2="384" y2="{{ $yPos }}"
          stroke="{{ $t['border'] }}" stroke-width="0.6"/>
    @php $yPos += 6; $sparkYOff = $yPos; @endphp
    <svg x="16" y="{{ $sparkYOff }}" width="368" height="36" viewBox="0 0 200 30" preserveAspectRatio="none">
        <polygon points="{{ $sparkPoints }} 200,30 0,30"
                 fill="url(#sparkFill)"/>
        <polyline points="{{ $sparkPoints }}"
                  fill="none" stroke="{{ $t['spark'] }}" stroke-width="1.5"
                  stroke-linecap="round" stroke-linejoin="round"/>
    </svg>
    @php $yPos += 40; @endphp
    @endif

    {{-- Footer --}}
    <text x="200" y="{{ $cardH - 10 }}" font-family="'Segoe UI', system-ui, sans-serif"
          font-size="8" fill="{{ $t['sub'] }}" text-anchor="middle" opacity="0.5">
        RepoWrapped · {{ config('app.url') }}
    </text>

</svg>
